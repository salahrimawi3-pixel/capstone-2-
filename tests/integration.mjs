const db = {
  async run(work) {
    const sql = query => query.replace(/\s+FOR UPDATE\b/g, '').replace(/FETCH FIRST (\d+) ROWS? ONLY/g, 'LIMIT $1').replace(/SYSTIMESTAMP/g, 'CURRENT_TIMESTAMP').replace(/TO_(DATE|CHAR)\(([^,]+), 'YYYY-MM-DD'\)/g, '$2').replace(/SELECT 1 AS READY FROM DUAL/g, 'SELECT 1 AS READY');
    oracleDialectTest.exec('BEGIN');
    try {
      const result = await work({
        rows: async (query, binds = {}) => oracleDialectTest.prepare(sql(query)).all(binds),
        execute: async (query, binds = {}) => ({ rowsAffected: oracleDialectTest.prepare(sql(query)).run(binds).changes }),
        insert: async (query, binds) => Number(oracleDialectTest.prepare(sql(query)).run(binds).lastInsertRowid),
      });
      oracleDialectTest.exec('COMMIT');
      return result;
    } catch (error) {
      oracleDialectTest.exec('ROLLBACK');
      throw error;
    }
  },
};

