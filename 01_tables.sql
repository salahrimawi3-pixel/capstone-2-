
SET DEFINE OFF;

BEGIN
  FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list(
    'BUS_ROUTE_STOPS','BUS_ROUTES','TRIP_STOPS','GPS_PINGS','INCIDENT_LOGS','AUDIT_LOGS','MATRIX_CACHE','TRIPS',
    'STUDENT_LOCATIONS','STUDENT_GUARDIANS','STUDENTS','BUSES','SCHOOLS','USER_PHONES','USERS'))) LOOP
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE ' || t.name || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION WHEN OTHERS THEN NULL; END;
  END LOOP;
END;
/

CREATE TABLE USERS (
  USER_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ROLE      VARCHAR2(10)  NOT NULL CHECK (USER_ROLE IN ('admin','driver','parent')),
  NAME           VARCHAR2(100) NOT NULL,
  EMAIL          VARCHAR2(150) NOT NULL UNIQUE,
  PASSWORD_HASH  VARCHAR2(100) NOT NULL,
  IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1)),
  CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE USER_PHONES (
  PHONE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID       NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  PHONE_NUMBER  VARCHAR2(20) NOT NULL,
  LABEL         VARCHAR2(30) DEFAULT 'Mobile',
  IS_PRIMARY    NUMBER(1) DEFAULT 0 NOT NULL CHECK (IS_PRIMARY IN (0,1))
);

CREATE TABLE SCHOOLS (
  SCHOOL_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME        VARCHAR2(150) NOT NULL UNIQUE,
  ADDRESS     VARCHAR2(250),
  LATITUDE    NUMBER(9,6) NOT NULL CHECK (LATITUDE BETWEEN -90 AND 90),
  LONGITUDE   NUMBER(9,6) NOT NULL CHECK (LONGITUDE BETWEEN -180 AND 180),
  START_TIME  VARCHAR2(5) DEFAULT '07:30'
);

CREATE TABLE BUSES (
  BUS_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PLATE_NUMBER  VARCHAR2(20) NOT NULL UNIQUE,
  SCHOOL_ID     NUMBER NOT NULL REFERENCES SCHOOLS(SCHOOL_ID),
  DRIVER_ID     NUMBER REFERENCES USERS(USER_ID),
  FUEL_TYPE     VARCHAR2(10) DEFAULT 'DIESEL' CHECK (FUEL_TYPE IN ('DIESEL','GASOLINE','HYBRID','ELECTRIC')),
  CAPACITY      NUMBER(3) DEFAULT 30 CHECK (CAPACITY > 0),
  IS_ACTIVE     NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1))
);

CREATE TABLE STUDENTS (
  STUDENT_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME        VARCHAR2(100) NOT NULL,
  SCHOOL_ID   NUMBER NOT NULL REFERENCES SCHOOLS(SCHOOL_ID),
  BUS_ID      NUMBER REFERENCES BUSES(BUS_ID),
  IS_ACTIVE   NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1))
);

-- A student can have many guardians, and a parent can have many students.
CREATE TABLE STUDENT_GUARDIANS (
  STUDENT_ID   NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID) ON DELETE CASCADE,
  USER_ID      NUMBER NOT NULL REFERENCES USERS(USER_ID),
  RELATION     VARCHAR2(30) DEFAULT 'Parent',
  CAN_PICK_UP  NUMBER(1) DEFAULT 1 NOT NULL CHECK (CAN_PICK_UP IN (0,1)),
  PRIMARY KEY (STUDENT_ID, USER_ID)
);

-- A student can have many pickup places.
-- DAYS: comma list like 'SUN,TUE' (NULL = every day). TRIP_TYPES: 'MORNING', 'AFTERNOON' (NULL = both).
CREATE TABLE STUDENT_LOCATIONS (
  LOCATION_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_ID   NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID) ON DELETE CASCADE,
  LABEL        VARCHAR2(50) NOT NULL,
  ADDRESS      VARCHAR2(250),
  PLACE_ID     VARCHAR2(100),
  LATITUDE     NUMBER(9,6) NOT NULL CHECK (LATITUDE BETWEEN -90 AND 90),
  LONGITUDE    NUMBER(9,6) NOT NULL CHECK (LONGITUDE BETWEEN -180 AND 180),
  IS_DEFAULT   NUMBER(1) DEFAULT 0 NOT NULL CHECK (IS_DEFAULT IN (0,1)),
  DAYS         VARCHAR2(30),
  TRIP_TYPES   VARCHAR2(20)
);

CREATE TABLE TRIPS (
  TRIP_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BUS_ID                 NUMBER NOT NULL REFERENCES BUSES(BUS_ID),
  DRIVER_ID              NUMBER NOT NULL REFERENCES USERS(USER_ID),
  SCHOOL_ID              NUMBER NOT NULL REFERENCES SCHOOLS(SCHOOL_ID),
  TRIP_TYPE              VARCHAR2(10) NOT NULL CHECK (TRIP_TYPE IN ('MORNING','AFTERNOON')),
  TRIP_DATE              DATE NOT NULL,
  STATUS                 VARCHAR2(12) DEFAULT 'PLANNED' NOT NULL CHECK (STATUS IN ('PLANNED','IN_PROGRESS','COMPLETED','CANCELLED')),
  STARTED_AT             TIMESTAMP,
  FINISHED_AT            TIMESTAMP,
  BASELINE_DISTANCE_M    NUMBER,
  BASELINE_DURATION_S    NUMBER,
  CURRENT_ROUTE_VERSION  NUMBER DEFAULT 0 NOT NULL,
  CONSTRAINT UQ_TRIP UNIQUE (BUS_ID, TRIP_DATE, TRIP_TYPE)
);

-- Each stop is a COPY of the student's pickup place for that trip (old trips stay correct if an address changes).
-- BASELINE_ORDER = the manual order. STOP_ORDER = the order the bus follows now.
CREATE TABLE TRIP_STOPS (
  TRIP_ID         NUMBER NOT NULL REFERENCES TRIPS(TRIP_ID) ON DELETE CASCADE,
  STOP_ORDER      NUMBER NOT NULL CHECK (STOP_ORDER >= 1),
  BASELINE_ORDER  NUMBER,
  STUDENT_ID      NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID),
  LATITUDE        NUMBER(9,6) NOT NULL,
  LONGITUDE       NUMBER(9,6) NOT NULL,
  ADDRESS         VARCHAR2(250),
  PLANNED_ETA     TIMESTAMP,
  ACTUAL_TIME     TIMESTAMP,
  STATUS          VARCHAR2(10) DEFAULT 'PENDING' NOT NULL CHECK (STATUS IN ('PENDING','PICKED_UP','DROPPED','ABSENT')),
  PRIMARY KEY (TRIP_ID, STOP_ORDER)
);

-- One row for every route made for a trip: version 1 = first route, version 2 = first re-route, ...
CREATE TABLE BUS_ROUTES (
  ROUTE_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRIP_ID           NUMBER NOT NULL REFERENCES TRIPS(TRIP_ID) ON DELETE CASCADE,
  VERSION           NUMBER NOT NULL CHECK (VERSION >= 1),
  REASON            VARCHAR2(15) NOT NULL CHECK (REASON IN ('INITIAL','TRAFFIC_DELAY','INCIDENT','OFF_ROUTE','ADMIN')),
  ALGORITHM         VARCHAR2(20) DEFAULT 'TWO_OPT' CHECK (ALGORITHM IN ('NEAREST_NEIGHBOR','TWO_OPT','GA','OR_TOOLS','GOOGLE_OPTIMIZE')),
  STATUS            VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL CHECK (STATUS IN ('ACTIVE','REPLACED','COMPLETED')),
  TOTAL_DISTANCE_M  NUMBER CHECK (TOTAL_DISTANCE_M >= 0),
  TOTAL_DURATION_S  NUMBER CHECK (TOTAL_DURATION_S >= 0),
  POLYLINE          CLOB,
  CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_ROUTE_VERSION UNIQUE (TRIP_ID, VERSION)
);

CREATE TABLE BUS_ROUTE_STOPS (
  ROUTE_ID       NUMBER NOT NULL REFERENCES BUS_ROUTES(ROUTE_ID) ON DELETE CASCADE,
  STOP_POSITION  NUMBER NOT NULL CHECK (STOP_POSITION >= 1),
  STUDENT_ID     NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID),
  PRIMARY KEY (ROUTE_ID, STOP_POSITION)
);

CREATE TABLE GPS_PINGS (
  PING_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRIP_ID    NUMBER NOT NULL REFERENCES TRIPS(TRIP_ID) ON DELETE CASCADE,
  BUS_ID     NUMBER NOT NULL REFERENCES BUSES(BUS_ID),
  TS         TIMESTAMP NOT NULL,
  LATITUDE   NUMBER(9,6) NOT NULL,
  LONGITUDE  NUMBER(9,6) NOT NULL,
  SPEED_KMH  NUMBER(5,1) CHECK (SPEED_KMH >= 0),
  HEADING    NUMBER(3) CHECK (HEADING BETWEEN 0 AND 360)
);
CREATE INDEX IX_GPS_TRIP_TS ON GPS_PINGS (TRIP_ID, TS);

CREATE TABLE INCIDENT_LOGS (
  INCIDENT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRIP_ID            NUMBER NOT NULL REFERENCES TRIPS(TRIP_ID) ON DELETE CASCADE,
  DETECTED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  INCIDENT_TYPE      VARCHAR2(10) NOT NULL CHECK (INCIDENT_TYPE IN ('ACCIDENT','CLOSURE','JAM','DELAY','SIMULATED')),
  SEVERITY           NUMBER(1) CHECK (SEVERITY BETWEEN 1 AND 5),
  LATITUDE           NUMBER(9,6),
  LONGITUDE          NUMBER(9,6),
  DELAY_SECONDS      NUMBER CHECK (DELAY_SECONDS >= 0),
  TRIGGERED_REROUTE  NUMBER(1) DEFAULT 0 NOT NULL CHECK (TRIGGERED_REROUTE IN (0,1))
);

-- Who did what and when. The backend writes here (a database trigger can be added later).
CREATE TABLE AUDIT_LOGS (
  AUDIT_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TS           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  USER_ID      NUMBER REFERENCES USERS(USER_ID) ON DELETE SET NULL,
  USER_ROLE    VARCHAR2(10),
  ACTION       VARCHAR2(50) NOT NULL,
  TARGET_TYPE  VARCHAR2(30),
  TARGET_ID    NUMBER,
  BEFORE_VALUE VARCHAR2(1000),
  AFTER_VALUE  VARCHAR2(1000),
  IP           VARCHAR2(45)
);

-- Saves Google matrix answers for a couple of minutes (the backend deletes old rows). Stays empty for now.
CREATE TABLE MATRIX_CACHE (
  CACHE_KEY    VARCHAR2(64) PRIMARY KEY,
  MATRIX_JSON  CLOB NOT NULL CONSTRAINT CK_MATRIX_JSON CHECK (MATRIX_JSON IS JSON),
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_STUDENTS_BUS ON STUDENTS (BUS_ID);
CREATE INDEX IX_TRIPS_STATUS ON TRIPS (STATUS);
CREATE INDEX IX_LOC_STUDENT ON STUDENT_LOCATIONS (STUDENT_ID);
CREATE INDEX IX_AUDIT_TS ON AUDIT_LOGS (TS);
